/// The glyphs of a version: v1 is capitals, digits and punctuation; v2 adds lowercase; v3 adds
/// `SYMBOLS`.
pub fn glyphs(version: u16) -> Vec<Glyph> {
    let mut v: Vec<Glyph> = BASIC.iter().chain(EXTRA_PUNCTUATION).copied().collect();
    if version >= 2 {
        v.extend_from_slice(LOWER);
    }
    if version >= 3 {
        v.extend_from_slice(SYMBOLS);
    }
    v
}

/// What scenes draw text with: every glyph there is.
pub fn text_glyphs() -> Vec<Glyph> {
    glyphs(3)
}

/// The "Orbital HUD" Regular font file for a version. Versions (1,0), (1,100), (2,0).
pub fn hud_font(version: u16) -> Vec<u8> {
    let glyphs = glyphs(version);
    let v = match version {
        1 => (1, 0),
        2 => (1, 100),
        _ => (2, 0),
    };
    ttf(&FontSpec {
        family: "Orbital HUD",
        style: "Regular",
        version: v,
        notice: "Orbital HUD, a fictional pixel font for the Orbital demo game. Drawn by hand.",
        glyphs: &glyphs,
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::media::check;

    fn ink_rows(g: &Glyph) -> Vec<usize> {
        (0..9).filter(|&r| g.rows[r].contains('#')).collect()
    }

    #[test]
    fn every_glyph_is_a_5x9_cell() {
        for g in glyphs(3) {
            assert!(g.rows.iter().all(|r| r.len() == 5 && r.bytes().all(|b| b == b'#' || b == b'.')), "{:?}", g.ch);
            assert!(!ink_rows(&g).is_empty(), "{:?} has ink", g.ch);
        }
    }

    #[test]
    fn each_version_adds_its_set() {
        let chars = |v| glyphs(v).iter().map(|g| g.ch).collect::<String>();
        for c in ('A'..='Z').chain('0'..='9').chain(".,:;!?-+/()'\"%#&_=*<>[]".chars()) {
            assert!(chars(1).contains(c), "v1 has {c:?}");
        }
        assert!(!chars(1).contains('a'));
        for c in 'a'..='z' {
            assert!(chars(2).contains(c), "v2 has {c:?}");
        }
        for c in "←↑→↓°·×ÉéèêàâçôöüñÄÖÜ\u{E000}\u{E001}\u{E002}\u{E003}\u{E004}\u{E005}".chars() {
            assert!(chars(3).contains(c), "v3 has {c:?}");
        }
        let mut all = chars(3).chars().collect::<Vec<_>>();
        let n = all.len();
        all.sort();
        all.dedup();
        assert_eq!(all.len(), n, "no character twice");
    }

    #[test]
    fn lowercase_sits_on_the_baseline_and_descenders_descend() {
        for g in LOWER {
            let rows = ink_rows(g);
            let descends = "gjpqy".contains(g.ch);
            assert_eq!(rows.iter().any(|&r| r >= 7), descends, "{:?} descender rows", g.ch);
            assert!(g.rows[6].contains('#') || descends, "{:?} touches the baseline", g.ch);
            if "bdfhklt".contains(g.ch) {
                assert!(rows[0] <= 1, "{:?} has an ascender", g.ch);
            } else if g.ch != 'i' && g.ch != 'j' {
                assert!(rows[0] >= 2, "{:?} stays at x-height", g.ch);
            }
        }
    }

    #[test]
    fn capitals_and_digits_fill_rows_0_to_6_only() {
        for g in glyphs(1).iter().filter(|g| g.ch.is_ascii_uppercase() || g.ch.is_ascii_digit()) {
            assert_eq!((ink_rows(g)[0], *ink_rows(g).last().unwrap()), (0, 6), "{:?}", g.ch);
        }
    }

    #[test]
    fn glyphs_are_distinct() {
        let all = glyphs(3);
        for (i, a) in all.iter().enumerate() {
            for b in &all[i + 1..] {
                assert_ne!(a.rows, b.rows, "{:?} and {:?} look the same", a.ch, b.ch);
            }
        }
    }

    #[test]
    fn the_font_grows_by_version() {
        let sizes: Vec<usize> = (1..=3).map(|v| hud_font(v).len()).collect();
        assert!(sizes[0] < sizes[1] && sizes[1] < sizes[2], "{sizes:?}");
        assert_eq!(hud_font(2), hud_font(2), "deterministic");
    }

    #[test]
    fn hud_fonts_load_in_pillow() {
        for v in 1..=3 {
            let Some(((mask_w, mask_h), (box_w, box_h))) = check::pillow_font(&hud_font(v)) else { return };
            eprintln!("Orbital HUD v{v}: mask {mask_w}x{mask_h}, bbox {box_w}x{box_h}");
            assert!(mask_w > 0 && mask_h > 0 && box_w > 0 && box_h > 0, "v{v} draws Ag0");
        }
    }
}
