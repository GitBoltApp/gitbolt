// Writes src/diff/shikiLanguages.ts: Shiki's language registry (shiki/langs) without the grammars
// build/license-exceptions.json drops for their licenses (docs/licensing.md), and with GitBolt's
// own grammar files (src/diff/grammars/<id>.json) for the ones it replaces. Shiki's own registry
// imports every grammar it ships, so importing it would put the dropped and replaced ones in the
// bundle; this copy names each kept grammar's module instead. Rerun after a Shiki upgrade, or
// after changing the dropped or replaced lists: `node scripts/gen-shiki-languages.mjs`
// (shikiLanguages.test.ts fails until then).
import { readFileSync, writeFileSync } from 'node:fs';
import { bundledLanguagesInfo } from 'shiki/langs';

const here = (p) => new URL(p, import.meta.url);
const shiki = JSON.parse(readFileSync(here('../node_modules/shiki/package.json'), 'utf8')).version;
const exceptions = JSON.parse(readFileSync(here('../build/license-exceptions.json'), 'utf8'));
const dropped = Object.keys(exceptions.dropped?.grammars ?? {});
const replaced = Object.keys(exceptions.replaced?.grammars ?? {});

const kept = bundledLanguagesInfo.filter((l) => !dropped.includes(l.id));
const q = (s) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const entry = (l) => {
  const aliases = l.aliases?.length ? `, aliases: [${l.aliases.map(q).join(', ')}]` : '';
  const load = replaced.includes(l.id) ? `own(import('./grammars/${l.id}.json', { with: { type: 'json' } }))` : `import('shiki/langs/${l.id}.mjs')`;
  return `  { id: ${q(l.id)}, name: ${q(l.name)}${aliases}, import: () => ${load} },`;
};

const out = `// Generated by scripts/gen-shiki-languages.mjs from Shiki ${shiki}'s shiki/langs: do not edit.
// Shiki's language registry without the grammars build/license-exceptions.json drops for their
// licenses (docs/licensing.md): ${dropped.join(', ')}.
// GitBolt's own grammar files (src/diff/grammars) replace Shiki's ${replaced.join(', ')}, whose
// upstream states no license. Import this, never shiki/langs, so the dropped and replaced grammars
// stay out of the bundle. Like shiki/langs, it belongs to the lazy diff chunk (language.ts).
import type { DynamicImportLanguageRegistration, LanguageRegistration } from 'shiki/core';

export interface BundledLanguageInfo {
  id: string;
  name: string;
  aliases?: string[];
  import: DynamicImportLanguageRegistration;
}

/** One of GitBolt's own grammar files (a tmLanguage JSON) as a Shiki grammar module. */
const own = (json: Promise<{ default: unknown }>) => json.then((m) => ({ default: [m.default as LanguageRegistration] }));

export const bundledLanguagesInfo: BundledLanguageInfo[] = [
${kept.map(entry).join('\n')}
];

/** Every id and alias → its grammar's import, as shiki/langs' \`bundledLanguages\`. */
export const bundledLanguages: Record<string, DynamicImportLanguageRegistration> = Object.fromEntries([
  ...bundledLanguagesInfo.map((l) => [l.id, l.import] as const),
  ...bundledLanguagesInfo.flatMap((l) => (l.aliases ?? []).map((a) => [a, l.import] as const)),
]);
`;
writeFileSync(here('../src/diff/shikiLanguages.ts'), out);
console.log(`shikiLanguages.ts: ${kept.length} languages (dropped ${dropped.length}: ${dropped.join(', ')}; GitBolt's own: ${replaced.join(', ')})`);
