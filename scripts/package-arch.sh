#!/usr/bin/env bash
# Usage: scripts/package-arch.sh <package.deb> [out-dir]
#
# Turns the built (and fix-deb'ed) .deb into an Arch package, GitVolt-<ver>-1-x86_64.pkg.tar.zst,
# without makepkg (the build machine is Ubuntu). out-dir defaults to target/release/bundle/arch.
#   payload  = the .deb's data member: same paths and modes (chrome-sandbox stays root:root 4755),
#              plus usr/share/licenses/gitvolt -> ../doc/gitvolt (the license notices); the
#              AppStream metainfo's <pkgname> becomes gitvolt
#   .PKGINFO = pacman's key = value metadata; depends mapped from the .deb's Depends through the
#              table in scripts/arch-pkg.py (an unknown Debian name fails the build); license =
#              MIT and the licenses of what the package bundles (arch-pkg.py licenses)
#   .MTREE   = gzip'd mtree of .PKGINFO and the payload, as makepkg's bsdtar writes it
# Archive order: .PKGINFO, .MTREE, then the payload; GNU tar, every entry root:root with one fixed
# mtime (the version's +YYYYMMDDHHMM build stamp, or $SOURCE_DATE_EPOCH), zstd -19.
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
helper="$here/arch-pkg.py"
deb=$(realpath "${1:?usage: package-arch.sh <package.deb> [out-dir]}")
out=${2:-target/release/bundle/arch}
fail() { echo "package-arch: $*" >&2; exit 1; }
[ -f "$deb" ] || fail "no such file: $deb"
mkdir -p "$out"
out=$(realpath "$out")

debver=$(dpkg-deb -f "$deb" Version)
pkgver=$(python3 "$helper" pkgver "$debver")-1
epoch=${SOURCE_DATE_EPOCH:-$(python3 "$helper" stamp "$debver" 2>/dev/null || stat -c %Y "$deb")}
pkgdesc=$(dpkg-deb -f "$deb" Description | head -1)
mapfile -t depends < <(python3 "$helper" depends "$(dpkg-deb -f "$deb" Depends)")
[ ${#depends[@]} -gt 0 ] || fail "no dependencies mapped"

# The work dir sits next to the output, not in /tmp (often tmpfs): the payload is ~350 MB.
work=$(mktemp -d "$out/.work.XXXXXX"); trap 'rm -rf "$work"' EXIT
(cd "$work" && ar x "$deb")
[ -f "$work/debian-binary" ] || fail "not a .deb: $deb"
data=$(cd "$work" && ls data.tar.*)
case "$data" in
  *.gz) unpack=(gzip -dc) ;;
  *.xz) unpack=(xz -dc) ;;
  *.zst) unpack=(zstd -dcq) ;;
  *.tar) unpack=(cat) ;;
  *) fail "unknown data member compression: $data" ;;
esac
"${unpack[@]}" "$work/$data" > "$work/data.tar"
rm "$work/$data"
mkdir "$work/pkg"
# -p keeps the recorded modes (the owner may set setuid on its own file); a normal user can't
# chown, so ownership is set in the archive below instead.
tar -xpf "$work/data.tar" -C "$work/pkg" --no-same-owner
[ -e "$work/pkg/.PKGINFO" ] && fail "the .deb's payload has a .PKGINFO"
sandbox=$(find "$work/pkg" -name chrome-sandbox -type f)
[ -n "$sandbox" ] || fail "no chrome-sandbox in the payload"
chmod 4755 "$sandbox" # as the deb ships it; never drop the setuid bit

# The license notices (docs/licensing.md) are in the .deb's /usr/share/doc/gitvolt/. Arch looks
# for license files in /usr/share/licenses/<pkg>/, so that is a symlink to the same directory.
for f in LICENSE THIRD-PARTY-NOTICES-rust.txt THIRD-PARTY-NOTICES-ui.txt CEF-LICENSE.txt CHROMIUM-CREDITS.html.gz DICTIONARY-en-US-LICENSE.txt; do
  [ -s "$work/pkg/usr/share/doc/gitvolt/$f" ] || fail "the .deb has no usr/share/doc/gitvolt/$f (or it's empty)"
done
# The spell-check dictionary the app copies into Chromium's profile (PRIVACY.md).
[ -s "$work/pkg/usr/share/GitVolt/dictionaries/en-US-10-1.bdic" ] ||
  fail "the .deb has no usr/share/GitVolt/dictionaries/en-US-10-1.bdic (or it's empty)"
# How the package was installed (the update check picks the Arch package by it): `arch`, where
# the .deb says `deb` (an edited file for arch-pkg.py verify, below).
[ "$(cat "$work/pkg/usr/share/GitVolt/install-kind" 2>/dev/null)" = deb ] || fail "the .deb has no usr/share/GitVolt/install-kind saying deb"
printf 'arch\n' > "$work/pkg/usr/share/GitVolt/install-kind"
[ -e "$work/pkg/usr/share/licenses/gitvolt" ] && fail "the .deb's payload already has usr/share/licenses/gitvolt"
mkdir -p "$work/pkg/usr/share/licenses"
chmod 755 "$work/pkg/usr/share/licenses"
ln -s ../doc/gitvolt "$work/pkg/usr/share/licenses/gitvolt"
mapfile -t licenses < <(python3 "$helper" licenses "$work/pkg/usr/share/doc/gitvolt")
[ ${#licenses[@]} -gt 0 ] || fail "no licenses found"

# The AppStream metainfo's <pkgname> is the .deb's package name (gitvolt); a software centre
# matches the installed component to its package by it, so here it's this package's.
debpkg=$(dpkg-deb -f "$deb" Package)
edited=(usr/share/GitVolt/install-kind)
for m in "$work"/pkg/usr/share/metainfo/*.metainfo.xml; do
  [ -e "$m" ] || continue
  grep -qF "<pkgname>$debpkg</pkgname>" "$m" || fail "$(basename "$m") doesn't name the .deb's package, $debpkg"
  sed -i "s|<pkgname>$debpkg</pkgname>|<pkgname>gitvolt</pkgname>|" "$m"
  edited+=("${m#"$work/pkg/"}")
done

size=$(python3 "$helper" size "$work/pkg")
{
  echo "# Generated by scripts/package-arch.sh from $(basename "$deb")"
  echo "pkgname = gitvolt"
  echo "pkgbase = gitvolt"
  echo "xdata = pkgtype=pkg"
  echo "pkgver = $pkgver"
  echo "pkgdesc = $pkgdesc"
  echo "url = https://github.com/GitVoltApp/gitvolt"
  echo "builddate = $epoch"
  echo "packager = GitVolt build"
  echo "size = $size"
  echo "arch = x86_64"
  printf 'license = %s\n' "${licenses[@]}"
  printf 'depend = %s\n' "${depends[@]}"
  # GitBolt's package (the app's name before 0.7.0): pacman removes it for this one.
  echo "conflict = gitbolt<0.7.0"
  echo "replaces = gitbolt<0.7.0"
} > "$work/pkg/.PKGINFO"
chmod 644 "$work/pkg/.PKGINFO"
python3 "$helper" mtree "$work/pkg" "$epoch" "$work/pkg/.MTREE"
chmod 644 "$work/pkg/.MTREE"

name="GitVolt-$pkgver-x86_64.pkg.tar.zst"
mapfile -t payload < <(cd "$work/pkg" && find . -mindepth 1 -maxdepth 1 ! -name '.*' -printf '%P\n' | LC_ALL=C sort)
tar -C "$work/pkg" --format=gnu --sort=name --mtime="@$epoch" \
    --owner=root:0 --group=root:0 --no-recursion -cf "$work/meta.tar" .PKGINFO .MTREE
tar -C "$work/pkg" --format=gnu --sort=name --mtime="@$epoch" \
    --owner=root:0 --group=root:0 -rf "$work/meta.tar" "${payload[@]}"
mv "$work/meta.tar" "$work/pkg.tar"

# The payload must match the .deb entry for entry (plus the licenses symlink), and stay root-owned
# and setuid.
python3 "$helper" verify "$work/data.tar" "$work/pkg.tar" "${edited[@]}" >/dev/null
[ "$(tar -tf "$work/pkg.tar" | head -2 | tr '\n' ' ')" = ".PKGINFO .MTREE " ] || fail "the archive doesn't start with .PKGINFO, .MTREE"
[ "$(tar -xOf "$work/pkg.tar" usr/share/GitVolt/install-kind)" = arch ] || fail "the package's install-kind isn't arch"
line=$(tar -tvf "$work/pkg.tar" | grep '/chrome-sandbox$') || fail "no chrome-sandbox in the package"
[[ $line == -rwsr-xr-x\ root/root* ]] || fail "chrome-sandbox is not root:root 4755: $line"

rm -f "$out"/GitVolt-*-x86_64.pkg.tar.zst
zstd -19 -T0 -q --rm "$work/pkg.tar" -o "$out/$name"
echo "package-arch: $out/$name ($(du -h "$out/$name" | cut -f1)); pkgver $pkgver; depends: ${depends[*]}"
